use futures_util::{SinkExt, StreamExt};
use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::TcpListener;
use tokio_tungstenite::tungstenite::Message;

#[derive(Clone)]
pub struct MockCdpConfig {
    pub response_markdown: String,
    pub stream_poll_count: usize,
    pub inject_error: bool,
    pub stale_response: Option<String>,
    pub plan_only: bool,
}

impl Default for MockCdpConfig {
    fn default() -> Self {
        Self {
            response_markdown: "# Default Mock Response\n\nGenerated by fake CDP.".into(),
            stream_poll_count: 1,
            inject_error: false,
            stale_response: None,
            plan_only: false,
        }
    }
}

pub struct MockCdpServer {
    pub base_url: String,
    pub ws_url: String,
    _shutdown: tokio::sync::oneshot::Sender<()>,
    pub calls: Arc<std::sync::Mutex<Vec<String>>>,
}

impl MockCdpServer {
    pub async fn start(config: MockCdpConfig) -> Self {
        Self::start_with_state(config, serde_json::json!({"login":"signed_in", "model":"Fast", "models":["Fast", "Thinking", "Pro"], "gems":[]})).await
    }

    pub async fn start_with_state(config: MockCdpConfig, observation: serde_json::Value) -> Self {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let base_url = format!("http://127.0.0.1:{port}");
        let ws_url = format!("ws://127.0.0.1:{port}/devtools/page/test-page-1");

        let (shutdown_tx, mut shutdown_rx) = tokio::sync::oneshot::channel::<()>();
        let config = Arc::new(config);
        let calls = Arc::new(std::sync::Mutex::new(Vec::new()));
        let server_calls = calls.clone();
        let stream_counter = Arc::new(AtomicUsize::new(0));
        let plan_approved = Arc::new(std::sync::atomic::AtomicBool::new(false));

        tokio::spawn(async move {
            loop {
                tokio::select! {
                    _ = &mut shutdown_rx => {
                        break;
                    }
                    accept_res = listener.accept() => {
                        let (mut stream, _) = match accept_res {
                            Ok(conn) => conn,
                            Err(_) => break,
                        };

                        let cfg = config.clone();
                        let observation = observation.clone();
                        let calls = server_calls.clone();
                        let stream_count = stream_counter.clone();
                        let approved = plan_approved.clone();
                        let server_port = port;

                        tokio::spawn(async move {
                            let mut peek_buf = [0u8; 1024];
                            let n = match stream.peek(&mut peek_buf).await {
                                Ok(n) if n > 0 => n,
                                _ => return,
                            };

                            let peek_str = String::from_utf8_lossy(&peek_buf[..n]);

                            if peek_str.contains("Upgrade: websocket") || peek_str.contains("upgrade: websocket") {
                                // Handle WebSocket connection
                                if let Ok(mut ws) = tokio_tungstenite::accept_async(stream).await {
                                    while let Some(msg_res) = ws.next().await {
                                        let msg = match msg_res {
                                            Ok(Message::Text(t)) => t,
                                            Ok(Message::Close(_)) | Err(_) => break,
                                            _ => continue,
                                        };

                                        let val: serde_json::Value = match serde_json::from_str(&msg) {
                                            Ok(v) => v,
                                            Err(_) => continue,
                                        };

                                        let id = val.get("id").and_then(|v| v.as_u64()).unwrap_or(0);
                                        let method = val.get("method").and_then(|v| v.as_str()).unwrap_or("");

                                        calls.lock().unwrap().push(method.into());
                                        let resp = match method {
                                            "Page.enable" | "Runtime.enable" | "DOM.enable" | "Page.navigate"
                                            | "Input.insertText" => {
                                                serde_json::json!({
                                                    "id": id,
                                                    "result": {}
                                                })
                                            }
                                            "Target.createTarget" => {
                                                serde_json::json!({
                                                    "id": id,
                                                    "result": {
                                                        "targetId": "mock-created-page-1"
                                                    }
                                                })
                                            }
                                            "Target.attachToTarget" => {
                                                serde_json::json!({
                                                    "id": id,
                                                    "result": {
                                                        "sessionId": "mock-session-id-1"
                                                    }
                                                })
                                            }
                                            "Target.closeTarget" => {
                                                serde_json::json!({
                                                    "id": id,
                                                    "result": {
                                                        "success": true
                                                    }
                                                })
                                            }
                                            "Target.getTargets" => {
                                                serde_json::json!({
                                                    "id": id,
                                                    "result": {
                                                        "targetInfos": []
                                                    }
                                                })
                                            }
                                            "Runtime.evaluate" => {
                                                if cfg.inject_error {
                                                    serde_json::json!({
                                                        "id": id,
                                                        "error": {
                                                            "code": -32000,
                                                            "message": "Injected synthetic evaluation failure"
                                                        }
                                                    })
                                                } else {
                                                    let expr = val.get("params")
                                                        .and_then(|p| p.get("expression"))
                                                        .and_then(|e| e.as_str())
                                                        .unwrap_or("");

                                                    let result_value = if expr.contains("gemini_axi_state") {
                                                        observation.clone()
                                                    } else if expr.contains("window.location.href") {
                                                        serde_json::json!("https://gemini.google.com/app")
                                                    } else if expr.contains("isPlan") || expr.contains("isProgressOnly") {
                                                        if cfg.plan_only {
                                                            serde_json::Value::Null
                                                        } else {
                                                            let count = stream_count.load(Ordering::SeqCst);
                                                            if count < cfg.stream_poll_count {
                                                                serde_json::Value::Null
                                                            } else {
                                                                serde_json::json!(cfg.response_markdown)
                                                            }
                                                        }
                                                    } else if expr.contains(".current-step") && expr.contains("activeSteps") {
                                                        serde_json::json!("Pesquisando em 12 sites...")
                                                    } else if expr.contains("nodeToMarkdown") || expr.contains("extract_new_response") {
                                                        if let Some(ref stale) = cfg.stale_response {
                                                            if expr.contains("initialCount = 1") {
                                                                let count = stream_count.load(Ordering::SeqCst);
                                                                if count < cfg.stream_poll_count {
                                                                    serde_json::Value::Null
                                                                } else {
                                                                    serde_json::json!(cfg.response_markdown)
                                                                }
                                                            } else if expr.contains("initialCount = 0") {
                                                                let count = stream_count.load(Ordering::SeqCst);
                                                                if count < cfg.stream_poll_count {
                                                                    serde_json::json!(stale)
                                                                } else {
                                                                    serde_json::json!(cfg.response_markdown)
                                                                }
                                                            } else {
                                                                serde_json::json!(cfg.response_markdown)
                                                            }
                                                        } else {
                                                            serde_json::json!(cfg.response_markdown)
                                                        }
                                                    } else if expr.contains("return matches.length;") {
                                                        let count = stream_count.load(Ordering::SeqCst);
                                                        if cfg.stale_response.is_some() {
                                                            if count < cfg.stream_poll_count {
                                                                serde_json::json!(1)
                                                            } else {
                                                                serde_json::json!(2)
                                                            }
                                                        } else if count < cfg.stream_poll_count {
                                                            serde_json::json!(0)
                                                        } else {
                                                            serde_json::json!(1)
                                                        }
                                                    } else if expr.contains("triggerClick") {
                                                        approved.store(true, Ordering::SeqCst);
                                                        serde_json::json!(true)
                                                    } else if expr.contains("planSelectors")
                                                        || (expr.contains("start research") && expr.contains("approveSelectors"))
                                                    {
                                                        if cfg.plan_only {
                                                            serde_json::json!(true)
                                                        } else if approved.load(Ordering::SeqCst) {
                                                            serde_json::json!(false)
                                                        } else {
                                                            serde_json::json!(true)
                                                        }
                                                    } else if expr.contains("is_app_ready")
                                                        || expr.contains("selectors = [\"rich-textarea")
                                                        || expr.contains("targetModel")
                                                        || expr.contains("triggers = [\"button")
                                                        || expr.contains("target.focus()")
                                                        || expr.contains("target.value = text")
                                                        || expr.contains("el.click();\n                    return true;")
                                                        || expr.contains("approveSelectors")
                                                        || expr.contains("targetText")
                                                        || expr.contains("user-query")
                                                        || expr.contains("Deep Research")
                                                        || expr.contains("ferramentas")
                                                    {
                                                        serde_json::json!(true)
                                                    } else if expr.contains("stopButtons") {
                                                        if cfg.plan_only || !approved.load(Ordering::SeqCst) {
                                                            serde_json::json!(false)
                                                        } else {
                                                            let count = stream_count.fetch_add(1, Ordering::SeqCst);
                                                            if count < cfg.stream_poll_count {
                                                                serde_json::json!(true)
                                                            } else {
                                                                serde_json::json!(false)
                                                            }
                                                        }
                                                    } else if expr.contains("stopSelectors")
                                                        || expr.contains("sendSelectors")
                                                    {
                                                        let count = stream_count.fetch_add(1, Ordering::SeqCst);
                                                        if count < cfg.stream_poll_count {
                                                            serde_json::json!(true)
                                                        } else {
                                                            serde_json::json!(false)
                                                        }
                                                    } else {
                                                        serde_json::json!(true)
                                                    };

                                                    serde_json::json!({
                                                        "id": id,
                                                        "result": {
                                                            "result": {
                                                                "type": if result_value.is_boolean() {
                                                                    "boolean"
                                                                } else if result_value.is_string() {
                                                                    "string"
                                                                } else if result_value.is_number() {
                                                                    "number"
                                                                } else {
                                                                    "object"
                                                                },
                                                                "value": result_value
                                                            }
                                                        }
                                                    })
                                                }
                                            }
                                            _ => {
                                                serde_json::json!({
                                                    "id": id,
                                                    "result": {}
                                                })
                                            }
                                        };

                                        let _ = ws.send(Message::Text(resp.to_string().into())).await;
                                    }
                                }
                            } else {
                                // Handle HTTP discovery endpoints
                                let mut req_buf = vec![0u8; 4096];
                                let _ = stream.read(&mut req_buf).await;

                                let (status, body) = if peek_str.starts_with("GET /json/version") {
                                    (
                                        "200 OK",
                                        serde_json::json!({
                                            "Browser": "MockChrome/1.0",
                                            "Protocol-Version": "1.3",
                                            "webSocketDebuggerUrl": format!("ws://127.0.0.1:{server_port}/devtools/browser/mock")
                                        }).to_string()
                                    )
                                } else if peek_str.starts_with("GET /json") || peek_str.starts_with("GET /json/list") {
                                    (
                                        "200 OK",
                                        serde_json::json!([
                                            {
                                                "id": "test-page-1",
                                                "type": "page",
                                                "title": "Gemini",
                                                "url": "https://gemini.google.com/app",
                                                "webSocketDebuggerUrl": format!("ws://127.0.0.1:{server_port}/devtools/page/test-page-1")
                                            }
                                        ]).to_string()
                                    )
                                } else if peek_str.starts_with("PUT /json/new") || peek_str.starts_with("GET /json/new") {
                                    (
                                        "200 OK",
                                        serde_json::json!({
                                            "id": "test-page-new",
                                            "type": "page",
                                            "title": "New Tab",
                                            "url": "https://gemini.google.com/app",
                                            "webSocketDebuggerUrl": format!("ws://127.0.0.1:{server_port}/devtools/page/test-page-new")
                                        }).to_string()
                                    )
                                } else {
                                    ("404 Not Found", "{}".into())
                                };

                                let response = format!(
                                    "HTTP/1.1 {status}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}",
                                    body.len()
                                );
                                let _ = stream.write_all(response.as_bytes()).await;
                                let _ = stream.flush().await;
                                let _ = stream.shutdown().await;
                            }
                        });
                    }
                }
            }
        });

        Self {
            base_url,
            ws_url,
            _shutdown: shutdown_tx,
            calls,
        }
    }
}
